from typing import List, Optional, Dict
from pydantic import BaseModel, Field

class SimplifiedArticle(BaseModel):
    title: str = Field(..., description="Headline of the financial news article")
    source: str = Field(..., description="Publishing news organization or source")
    author: Optional[str] = Field(None, description="Author of the article")
    published_at: Optional[str] = Field(None, description="ISO timestamp of article publication")
    url: Optional[str] = Field(None, description="Link to the original full article")
    image_url: Optional[str] = Field(None, description="Featured image or thumbnail URL")
    category: Optional[str] = Field("Markets", description="Topic category (Markets, Economy, Tech, etc.)")
    original_description: Optional[str] = Field(None, description="Original technical snippet from publisher")
    summary: str = Field(..., description="Simplified, jargon-free explanation generated by AI")
    key_takeaways: List[str] = Field(default_factory=list, description="Bullet points explaining impact & meaning")
    simplified_terms: Dict[str, str] = Field(default_factory=dict, description="Glossary of financial terms translated to plain English")

class NewsResponse(BaseModel):
    success: bool = True
    count: int = Field(..., description="Number of simplified articles returned")
    mode: str = Field("live", description="'live' (Groq + NewsAPI) or 'demo' (mock fallback)")
    model: str = Field("llama-3.3-70b-versatile", description="Model used for text simplification")
    articles: List[SimplifiedArticle] = Field(default_factory=list, description="List of simplified news articles")

class HealthResponse(BaseModel):
    status: str = "healthy"
    version: str = "1.0.0"
    app_name: str = "FinNews AI – Financial News Simplifier"
    groq_configured: bool = False
    newsapi_configured: bool = False
    model: str = "llama-3.3-70b-versatile"
    environment: str = "development"

class ErrorResponse(BaseModel):
    success: bool = False
    error: str
    detail: Optional[str] = None
